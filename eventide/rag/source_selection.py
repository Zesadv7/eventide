"""Versioned, narrow exclusions for source-oriented knowledge indexes."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import PurePosixPath
from typing import Literal

SourceScope = Literal["code", "all"]

_LOCK_FILES = (
    "Cargo.lock", "Gemfile.lock", "Pipfile.lock", "bun.lock", "bun.lockb",
    "composer.lock", "go.sum", "npm-shrinkwrap.json", "package-lock.json",
    "pnpm-lock.yaml", "poetry.lock", "uv.lock", "yarn.lock",
)
_OUTPUT_DIRS = (
    ".next", ".nuxt", ".vite", "__pycache__", "coverage", "dist", "node_modules",
)
_OUTPUT_SUFFIXES = (".min.js", ".min.css", ".js.map", ".css.map")
_GENERATED_PATTERNS = (
    r"This file was auto-generated by openapi-typescript\.",
    r"^// Code generated [^\n]+ DO NOT EDIT\.$",
)
GENERATED_HEADER_CHARS = 2048


def source_selection_identity(source_scope: str = "code") -> str:
    """Include exact rules in the frozen configuration; scope changes require rebuilding."""
    if source_scope not in {"code", "all"}:
        raise ValueError("source_scope must be 'code' or 'all'")
    return json.dumps(
        {
            "version": "source-selection-v1",
            "source_scope": source_scope,
            "lock_files": _LOCK_FILES,
            "output_dirs": _OUTPUT_DIRS,
            "output_suffixes": _OUTPUT_SUFFIXES,
            "generated_patterns": _GENERATED_PATTERNS,
            "generated_header_chars": GENERATED_HEADER_CHARS,
        },
        sort_keys=True, separators=(",", ":"),
    )


def source_selection_fingerprint(identity: str) -> str:
    return hashlib.sha256(identity.encode("utf-8")).hexdigest()


def exclusion_reason(path: str, *, header: str = "") -> str | None:
    """Return a fixed reason, never a caller-controlled path or generated label."""
    relative = PurePosixPath(path)
    if relative.name in _LOCK_FILES:
        return "dependency_lock"
    if any(part in _OUTPUT_DIRS for part in relative.parts[:-1]):
        return "build_output"
    if relative.name.endswith(_OUTPUT_SUFFIXES):
        return "build_output"
    if relative.suffix in {".ts", ".go"} and any(
        re.search(pattern, header[:GENERATED_HEADER_CHARS], re.MULTILINE)
        for pattern in _GENERATED_PATTERNS
    ):
        return "generated_artifact"
    return None
