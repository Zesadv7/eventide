"""Explainable corpus scope and safe reuse of published indexes."""

import json
import sqlite3
import subprocess
from dataclasses import replace
from pathlib import Path

import pytest

from eventide.rag import source_selection
from eventide.rag.chunker import chunking_fingerprint
from eventide.rag.embedding import HashEmbedder
from eventide.rag.index import IndexStore


@pytest.fixture
def store(tmp_path: Path) -> IndexStore:
    root = tmp_path / "repo"
    subprocess.run(["git", "init", "-q", str(root)], check=True, capture_output=True)
    return IndexStore(root, index_dir=tmp_path / "index")


def test_default_code_scope_skips_only_explicit_artifacts(store: IndexStore) -> None:
    kept = ["src/service.py", "config.json", "config.yaml", "types/custom.d.ts",
        "frontend/openapi.json", "build/tool.py", "eventide/workbench/assets/source.js"]
    excluded = [
        "uv.lock", "frontend/package-lock.json", "dist/main.js",
        "frontend/src/api/schema.d.ts", "client.min.js",
    ]
    for name in kept + excluded:
        path = store.workspace / name
        path.parent.mkdir(parents=True, exist_ok=True)
        text = "searchableneedle"
        if name == "frontend/src/api/schema.d.ts":
            text = "/** This file was auto-generated by openapi-typescript. */\n" + text
        path.write_text(text, encoding="utf-8")
    stats = store.build()
    assert stats.files == len(kept)
    assert stats.skipped == len(excluded)
    assert stats.skipped_reasons == {
        "dependency_lock": 2, "build_output": 2, "generated_artifact": 1,
    }
    assert stats.source_scope == "code"
    assert stats.source_selection_fingerprint
    hits = store.sparse_search("searchableneedle", limit=20)
    assert {item.chunk.file for item in hits} == set(kept)
    assert not (store.workspace / ".gitignore").exists()


def test_all_scope_requires_force_and_retains_original_safety(store: IndexStore) -> None:
    (store.workspace / "uv.lock").write_text("lockneedle", encoding="utf-8")
    (store.workspace / "code.py").write_text("codeneedle", encoding="utf-8")
    (store.workspace / "binary.dat").write_bytes(b"binary\0")
    first = store.build()
    with pytest.raises(ValueError, match="Source selection configuration changed"):
        store.build(source_scope="all")
    assert store.generation() == first.generation
    stats = store.build(source_scope="all", force=True)
    assert stats.files == 2 and stats.skipped_reasons == {"binary": 1}
    assert stats.source_selection_fingerprint != first.source_selection_fingerprint
    assert store.sparse_search("lockneedle", limit=5)[0].chunk.file == "uv.lock"
    assert store.build(source_scope="all").rebuilt_files == 0


def test_legacy_selection_is_readable_but_cannot_mix_new_build(store: IndexStore) -> None:
    (store.workspace / "code.py").write_text("historicalneedle", encoding="utf-8")
    store.build()
    with sqlite3.connect(store.path) as connection:
        connection.execute("DELETE FROM meta WHERE key LIKE 'source_selection_%'")
    assert store.sparse_search("historicalneedle", limit=5)
    with pytest.raises(ValueError, match="Source selection configuration changed"):
        store.build()
    assert store.build(force=True).rebuilt_files == 1


def test_invalid_scope_is_rejected_before_index_creation(store: IndexStore) -> None:
    with pytest.raises(ValueError, match="source_scope"):
        store.build(source_scope="unknown")
    assert not store.path.exists()


def test_empty_published_index_still_requires_force_to_change_scope(store: IndexStore) -> None:
    store.build()
    with pytest.raises(ValueError, match="Source selection configuration changed"):
        store.build(source_scope="all")
    assert store.build(source_scope="all", force=True).files == 0


def test_rule_change_requires_force_even_when_scope_is_unchanged(
    store: IndexStore, monkeypatch: pytest.MonkeyPatch,
) -> None:
    (store.workspace / "future.lock").write_text("futureneedle", encoding="utf-8")
    original = store.build()
    monkeypatch.setattr(
        source_selection, "_LOCK_FILES", (*source_selection._LOCK_FILES, "future.lock"),
    )
    with pytest.raises(ValueError, match="Source selection configuration changed"):
        store.build()
    assert store.generation() == original.generation
    assert store.sparse_search("futureneedle", limit=5)
    assert store.build(force=True).files == 0


def test_window_v1_remains_readable_and_requires_force(store: IndexStore) -> None:
    (store.workspace / "code.py").write_text("oldwindowneedle", encoding="utf-8")
    store.build()
    with sqlite3.connect(store.path) as connection:
        profile = json.loads(connection.execute(
            "SELECT value FROM meta WHERE key = 'chunking_profile'",
        ).fetchone()[0])
        profile["version"] = "windows-v1"
        encoded = json.dumps(profile, sort_keys=True, separators=(",", ":"))
        connection.executemany("UPDATE meta SET value = ? WHERE key = ?", [
            (encoded, "chunking_profile"),
            (chunking_fingerprint(encoded), "chunking_fingerprint"),
        ])
    assert store.sparse_search("oldwindowneedle", limit=5)
    with pytest.raises(ValueError, match="Chunking configuration changed"):
        store.build()
    assert store.build(force=True).rebuilt_files == 1


def test_generated_headers_are_bounded_and_not_filename_guesses(store: IndexStore) -> None:
    contents = {
        "client.go": "// Code generated by generator. DO NOT EDIT.\npackage client\n",
        "handwritten.d.ts": "export type Client = string;\n",
        "late.ts": " " * 2048 + "This file was auto-generated by openapi-typescript.",
        "guide.md": "This file was auto-generated by openapi-typescript.",
    }
    for name, body in contents.items():
        (store.workspace / name).write_text(body, encoding="utf-8")
    stats = store.build()
    assert stats.files == 3 and stats.skipped_reasons == {"generated_artifact": 1}
    assert store.build(source_scope="all", force=True).files == 4


def test_build_configuration_checks_legacy_location_without_writing(store: IndexStore) -> None:
    (store.workspace / "code.py").write_text("legacy_location_needle", encoding="utf-8")
    legacy = IndexStore(store.workspace)
    legacy.build(source_scope="all", code_structure=True)
    profile = legacy.embedding_profile()
    before = legacy.path.read_bytes()
    assert legacy.validate_build_configuration(
        profile, source_scope="all", code_structure=True,
    ) == profile
    for requested, options, message in [
        (profile, {"source_scope": "code", "code_structure": True}, "Source selection"),
        (profile, {"source_scope": "all", "code_structure": False}, "Chunking"),
        (replace(profile, model="changed"),
         {"source_scope": "all", "code_structure": True}, "Embedding"),
    ]:
        with pytest.raises(ValueError, match=message + " configuration changed"):
            legacy.validate_build_configuration(requested, **options)
    assert legacy.path.read_bytes() == before
    assert legacy.generation() == 1 and not store.path.exists()


@pytest.mark.parametrize("prefix", ["chunking", "source_selection"])
def test_readonly_build_configuration_requires_recorded_policy(
    store: IndexStore, prefix: str,
) -> None:
    (store.workspace / "code.py").write_text("unchanged_needle", encoding="utf-8")
    store.build()
    profile = store.embedding_profile()
    with sqlite3.connect(store.path) as connection:
        connection.execute("DELETE FROM meta WHERE key LIKE ?", (prefix + "_%",))
    with pytest.raises(ValueError, match="rebuild with --force"):
        store.validate_build_configuration(profile)
    assert store.sparse_search("unchanged_needle", limit=5)
    assert store.generation() == 1


def test_readonly_build_configuration_does_not_create_missing_index(store: IndexStore) -> None:
    (store.workspace / "code.py").write_text("needle", encoding="utf-8")
    store.build()
    missing = IndexStore(store.workspace)
    with pytest.raises(ValueError, match="No knowledge index"):
        missing.validate_build_configuration(store.embedding_profile())
    assert not missing.path.parent.exists()


def test_readonly_build_configuration_uses_one_generation(
    store: IndexStore, monkeypatch: pytest.MonkeyPatch,
) -> None:
    (store.workspace / "code.py").write_text("originalneedle", encoding="utf-8")
    store.build()
    profile = store.embedding_profile()
    original = IndexStore.validate_profile

    def change_after_policy_read(reader, requested):
        store.build(source_scope="all", force=True, embedder=HashEmbedder(),
                    profile=replace(profile, model="changed"))
        return original(reader, requested)

    monkeypatch.setattr(IndexStore, "validate_profile", change_after_policy_read)
    assert store.validate_build_configuration(profile) == profile
    assert store.generation() == 2
    with pytest.raises(ValueError, match="Source selection configuration changed"):
        store.validate_build_configuration(profile)
